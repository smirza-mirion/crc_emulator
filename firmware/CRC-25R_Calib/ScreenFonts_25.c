    void get_ch_array(uchar ch, short fontsize, uchar *ch_array)
    {
        
        size_t nb;
        int index;
    
        nb = fonts[fontsize].y * fonts[fontsize].nbytes;
    
        switch(fontsize)
        {
        case SMALL:
            memcpy(ch_array,char_5_7 + nb * (ch - ' '),nb);
            break;
        case MEDIUM:
            memcpy(ch_array,char_7_9 + nb * (ch - ' '),nb);
            break;
        case BIG:
            memcpy(ch_array,char_8_13 + nb * (ch - ' '),nb);
            break;
        case VBIG:
           index = strchr(vb,(int)ch) - strchr(vb,(int)'0');
           memcpy(ch_array,vbnum + nb * index,nb);
           break;
           
        default:
            break;
    
        }
    }
    
