void Mca_matchWipePeaks(WELLWIPEPEAK wipepeak[], float Threshold, WELLWIPENUCLIDE WellWipeNuclide[10], int NumOfChannels){
	short index, jndex, WellWipeNuclideIndex;
	long long int WellWipeNuclideID;
	float primaryEV, secondaryEV, tertiaryEV;

	// Search for Primary
	for(index=0; index<40; index++){
		if(wipepeak[index].Energy >= 0){
			WellWipeNuclideIndex = Mca_findMatchingWipe(wipepeak[index].Energy, WellWipeNuclide, NumOfChannels);
			if(WellWipeNuclideIndex >= 0){
				wipepeak[index].WellWipeNuclideID = WellWipeNuclide[WellWipeNuclideIndex].WellWipeNuclideID;
				wipepeak[index].PeakType = PRIMARY;
				wipepeak[index].Activity = wipepeak[index].NetROICPM / (0.01 * WellWipeNuclide[WellWipeNuclideIndex].Efficiency);
				if(wipepeak[index].Activity > Threshold){
					wipepeak[index].ExceedsThreshold = TRUE;
				}else{
					wipepeak[index].ExceedsThreshold = FALSE;
				}
			}
		}else{
			break;
		}
	}

	// Search for Secondary, Tertiary and Summed Peaks
	for(index=0; index<40; index++){
		if(wipepeak[index].Energy >= 0){
			if(wipepeak[index].PeakType == PRIMARY){
				WellWipeNuclideID = wipepeak[index].WellWipeNuclideID;

				primaryEV = 0.0;
				secondaryEV = 0.0;
				tertiaryEV = 0.0;

				// Search for WELLWIPENUCLIDE, get SecondaryEV and get TertiaryEV
				for(jndex=0; jndex<10; jndex++){
					if(WellWipeNuclide[jndex].WellWipeNuclideID == WellWipeNuclideID){
						primaryEV = WellWipeNuclide[jndex].PrimaryEnergy;
						secondaryEV = WellWipeNuclide[jndex].SecondaryEnergy;
						tertiaryEV = WellWipeNuclide[jndex].TertiaryEnergy;
						break;
					}
				}

				// Scan and Mark Secondary
				for(jndex=0; jndex<40; jndex++){
					if(wipepeak[jndex].Energy >= 0){
						if(wipepeak[jndex].PeakType == NOT_FOUND){
							if(Mca_isMatch(wipepeak[jndex].Energy, primaryEV, secondaryEV, tertiaryEV, SECONDARY, NumOfChannels)){
								wipepeak[jndex].WellWipeNuclideID = WellWipeNuclideID;
								wipepeak[jndex].PeakType = SECONDARY;
								break;
							}
						}
					}else{
						break;
					}
				}

				// Scan and Mark Tertiary
				for(jndex=0; jndex<40; jndex++){
					if(wipepeak[jndex].Energy >= 0){
						if(wipepeak[jndex].PeakType == NOT_FOUND){
							if(Mca_isMatch(wipepeak[jndex].Energy, primaryEV, secondaryEV, tertiaryEV, TERTIARY, NumOfChannels)){
								wipepeak[jndex].WellWipeNuclideID = WellWipeNuclideID;
								wipepeak[jndex].PeakType = TERTIARY;
								break;
							}
						}
					}else{
						break;
					}
				}

				// Scan and Mark Summed
				for(jndex=0; index<40; jndex++){
					if(wipepeak[jndex].Energy >= 0){
						if(wipepeak[jndex].PeakType == NOT_FOUND){
							if(Mca_isMatch(wipepeak[jndex].Energy, primaryEV, secondaryEV, tertiaryEV, SUMMED, NumOfChannels)){
								wipepeak[jndex].WellWipeNuclideID = WellWipeNuclideID;
								wipepeak[jndex].PeakType = SUMMED;
								break;
							}
						}
					}else{
						break;
					}
				}
			}
		}else{
			break;
		}
	}
}

