static int McaLoadDSP(void){
	int i, iReturn, iProgLen;
	unsigned short int *uspValue;
	unsigned short int usValue;
	unsigned short int usMCAFlag;
	unsigned char ucOK;
	ulong onesec;

	iReturn = 0;
	//reset DSP then release
	usMCAFlag = 0;
	write_mca_port(DSPSYSCONTROL, usMCAFlag);
	delay_msec(2);
	usMCAFlag = 0x40;
	write_mca_port(DSPSYSCONTROL, usMCAFlag);

	MCASetAddress(1);

	iProgLen = sizeof(m_ucDspCode);
	iProgLen /= 3;

	// Load Program into DSP
	for(i=1; i<iProgLen; i++){
		uspValue = (unsigned short int *) (&(m_ucDspCode[3*i]));
		usValue = m_ucDspCode[(3*i) + 2];
		MCAWriteData(*uspValue);
		MCAWriteData(usValue);
	}

	// Check program was written correctly
	ucOK = 0xff;
	MCASetAddress(1);
	for(i=1; i<iProgLen; i++){
		uspValue = (unsigned short int *) (&(m_ucDspCode[3*i]));
		usValue = m_ucDspCode[(3*i) + 2];

		if(MCAReadData()==(*uspValue)){
			if(MCAReadData()!=usValue){
				ucOK = 0;
				break;
			}
		}else{
			ucOK = 0;
			break;
		}
	}

	if(ucOK){
		// Start DSP by writing to first code
		MCASetAddress(0);
		uspValue = (unsigned short int *) (&(m_ucDspCode[0]));
		usValue = m_ucDspCode[2];
		MCAWriteData(*uspValue);
		MCAWriteData(usValue);

		onesec = g_csec_tstamp + 100;
		do{
			MCASetAddress(SW_CONTROL_REG);
			usValue = MCAReadData();
			service_watchdog();
		}while((usValue!=0x8000) && (onesec > g_csec_tstamp));

		if((usValue & 0x8000)==0x8000){
			iReturn = MCAClearChannels(1);
			if(!iReturn){
				MCASetAddress(SW_CONTROL_REG);
				usValue = MCAReadData();
				if(usValue!=0x8001){
					// DSP is not running
					iReturn = ERR_MCA_PROG_NOT_RUNNING;
				}
			}else{
				iReturn = ERR_MCA_PROG_NOT_RUNNING;
			}
		}else{
			iReturn = ERR_MCA_PROG_NOT_RUNNING;
		}
	}else{
		// Data Write failed
		iReturn = ERR_MCA_PROG_LOAD_FAILURE;
	}
	return iReturn;
}

