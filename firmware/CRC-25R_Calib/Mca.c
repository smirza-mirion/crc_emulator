float Mca_getCpm(ulong spectrum[], short startCh, short endCh, float liveSeconds, bool subtractBackground){
	short index;
	ulong total;
	double rate, bkgrate;
	double seconds;
	float returnValue;

	if(liveSeconds>0){
		seconds = liveSeconds;
		total = 0;
		for(index=startCh; index<=endCh; index++) total += spectrum[index];

		rate = total;
		rate /= seconds; // Cps
		rate *= 60; // Cpm
		if(subtractBackground){
			total = 0;
			for(index=startCh; index<=endCh; index++) total += activeBkgMirror->Spectrum.DecompressedSpectra[index];
			bkgrate = total;
			bkgrate /= activeBkgMirror->Spectrum.LiveTime;
			bkgrate *= 60;
			rate -= bkgrate;
		}
		returnValue = rate;
	}
	else returnValue = 0;

	return returnValue;
}

