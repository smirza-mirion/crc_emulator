void Mca_dedupPeaks(PEAK detectpeak[], short secondregionstart, int numOfChannels){
	short index, jndex, totalpeaks, tempPeakEnd;
	float secondpeakcentroid, proximityThreshold;
	PEAK tempPeak[40];
	bool found;

	proximityThreshold = numOfChannels;
	proximityThreshold /= 256.0;
	proximityThreshold *= 2.0;

	totalpeaks = 0;
	tempPeakEnd = 0;
	for(index=0; index<40; index++){
		if(detectpeak[index].height > 0.0) totalpeaks++;
	}

	if((secondregionstart == 0) || (totalpeaks == secondregionstart) || (totalpeaks == 0)){
		// Only peaks in region two (secondregionstart == 0)
		// Only peaks in region one (totalpeaks == secondregionstart)
		// No peaks (totalpeaks == 0)
		// Do Nothing, Nothing to Dedup
	}else{
		for(index=0; index<40; index++){
			tempPeak[index].centroid = 0;
			tempPeak[index].height = 0;
		}

		// copy first region to tempPeak

		for(index=0; index<secondregionstart; index++){
			tempPeak[index].centroid = detectpeak[index].centroid;
			tempPeak[index].height = detectpeak[index].height;
		}
		tempPeakEnd = secondregionstart;

		// scan second for duplicated and replace the values into the tempPeak;
		for(index=secondregionstart; index<40; index++){
			if(detectpeak[index].height > 0.0){
				secondpeakcentroid = detectpeak[index].centroid;
				found = FALSE;
				for(jndex=0; jndex<secondregionstart; jndex++){
					if(fabs((detectpeak[jndex].centroid - secondpeakcentroid)) < proximityThreshold){
						tempPeak[jndex].centroid = detectpeak[index].centroid;
						tempPeak[jndex].height = detectpeak[index].height;
						found = TRUE;
						break;
					}
				}

				if(!found){
					tempPeak[tempPeakEnd].centroid = detectpeak[index].centroid;
					tempPeak[tempPeakEnd].height = detectpeak[index].height;
					tempPeakEnd++;
				}
			}else{
				break;
			}
		}

		for(index=0; index<40; index++){
			detectpeak[index].centroid = tempPeak[index].centroid;
			detectpeak[index].height = tempPeak[index].height;
		}
	}
}

