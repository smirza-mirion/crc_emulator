bool Mca_isMatch(float energy, float primaryEV, float secondaryEV, float tertiaryEV, short type, int numOfChannels){
	bool returnValue;
	float nucEnergy, nucEnergy1, nucEnergy2, lowerLimit, upperLimit;

	nucEnergy = 0.0;
	switch(type){
		case SECONDARY:
			nucEnergy = secondaryEV;
			break;

		case TERTIARY:
			nucEnergy = tertiaryEV;
			break;

		case SUMMED:
			nucEnergy1 = primaryEV;
			nucEnergy2 = secondaryEV;
			if((nucEnergy1 > 0.0) && (nucEnergy2 > 0.0)){
				nucEnergy = nucEnergy1 + nucEnergy2;
			}else{
				nucEnergy = 0.0;
			}
			break;
	}

	if(nucEnergy>0.0){
		Mca_getEnergyLimits(energy, &lowerLimit, &upperLimit, numOfChannels);
		if((nucEnergy <= upperLimit) && (nucEnergy >= lowerLimit)){
			returnValue = TRUE;
		}else{
			returnValue = FALSE;
		}
	}else{
		returnValue = FALSE;
	}

	return returnValue;
}

