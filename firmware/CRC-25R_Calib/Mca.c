int Mca_setup(void){
	int iReturn;
	ushort detector;
	char acCapMcaIDStr[7];
	
	DB_PopWellTime();

	DB_PopDetector(&detectorMirror, DET_WELL);
	DB_PopDetector(&detectorProbe700Mirror, DET_PROBE700);
	DB_PopDetector(&detectorWell700Mirror, DET_WELL700);

	DB_PopAutoCal(&wellAutoCalMirror, DET_WELL);
	DB_PopAutoCal(&betaAutoCalMirror, DET_BETA);
	DB_PopAutoCal(&probe700AutoCalMirror, DET_PROBE700);
	DB_PopAutoCal(&drilledprobe700AutoCalMirror, DET_DRILLEDPROBE700);
	DB_PopAutoCal(&well700AutoCalMirror, DET_WELL700);
	DB_PopAutoCal(&emptyAutoCalMirror, 999999);

	DB_PopBackground(&wellBkgMirror, DET_WELL);
	DB_PopBackground(&betaBkgMirror, DET_BETA);
	DB_PopBackground(&probe700BkgMirror, DET_PROBE700);
	DB_PopBackground(&drilledprobe700BkgMirror, DET_DRILLEDPROBE700);
	DB_PopBackground(&well700BkgMirror, DET_WELL700);
	DB_PopBackground(&emptyBkgMirror, 999999);

	strncpy(acCapMcaIDStr, detectorMirror.snum, 6);
	acCapMcaIDStr[6] = 0;
	Mca_testDetectorChange(acCapMcaIDStr, detectorMirror.threshold, detectorMirror.hv, DET_WELL, detectorMirror.num_of_channels);

	strncpy(acCapMcaIDStr, detectorProbe700Mirror.snum, 6);
	acCapMcaIDStr[6] = 0;
	Mca_testDetectorChange(acCapMcaIDStr, detectorProbe700Mirror.threshold, detectorProbe700Mirror.hv, DET_PROBE700, detectorProbe700Mirror.num_of_channels);
	Mca_testDetectorChange(acCapMcaIDStr, detectorProbe700Mirror.threshold, detectorProbe700Mirror.hv, DET_DRILLEDPROBE700, detectorProbe700Mirror.num_of_channels);

	strncpy(acCapMcaIDStr, detectorWell700Mirror.snum, 6);
	acCapMcaIDStr[6] = 0;
	Mca_testDetectorChange(acCapMcaIDStr, detectorWell700Mirror.threshold, detectorWell700Mirror.hv, DET_WELL700, detectorWell700Mirror.num_of_channels);

	// Test if MCA Board is installed
	if((McaReadID()==0x21) || (McaReadID()==0x31)){
		McaReadData(); // Read Mca data structure from i2c EEPROM on MCA board
		acCapMcaIDStr[6] = 0;
		strncpy(acCapMcaIDStr, mca_data.name, 6);

		// Check if MCA board has valid offset and zero
		if(strcmp(acCapMcaIDStr, "CapMca") == 0){
			if(McaReadID() == 0x21){
				detector = MCAGetDetector();

#ifdef ATTACHWELL
				if(ATTACHWELL) detector = 1;
#else
				if(current.demo_mode) detector = 1;
#endif
				if(detector == 1){
#ifdef USE_T_WELL_AS_PROBE
					detector = DET_PROBE700;
					activeAutoCalMirror = &probe700AutoCalMirror;
					activeBkgMirror = &probe700BkgMirror;
#else
					activeAutoCalMirror = &wellAutoCalMirror;
					activeBkgMirror = &wellBkgMirror;
					detectorMirror.installed = detector;
#endif
				}else if(detector == 2){
					activeAutoCalMirror = &betaAutoCalMirror;
					activeBkgMirror = &betaBkgMirror;
					detectorMirror.installed = detector;
				}else{
					detector = 6;
					activeAutoCalMirror = &emptyAutoCalMirror;
					activeBkgMirror = &emptyBkgMirror;
				}
#ifdef USE_T_WELL_AS_PROBE
				activeDetectorMirror = &detectorProbe700Mirror;
#else
				activeDetectorMirror = &detectorMirror;
#endif
			}else{
				if(detectorProbe700Mirror.installed != DET_EMPTY){
					detector = detectorProbe700Mirror.installed;
					if(detector == DET_PROBE700){
						activeAutoCalMirror = &probe700AutoCalMirror;
						activeBkgMirror = &probe700BkgMirror;
					}else{
						activeAutoCalMirror = &drilledprobe700AutoCalMirror;
						activeBkgMirror = &drilledprobe700BkgMirror;
					}
					activeDetectorMirror = &detectorProbe700Mirror;
				}else{
					detector = detectorWell700Mirror.installed;
					activeAutoCalMirror = &well700AutoCalMirror;
					activeBkgMirror = &well700BkgMirror;
					activeDetectorMirror = &detectorWell700Mirror;
				}
			}

			if((detector == 1) || (detector == 2) || (detector == 3) || (detector == 4) || (detector == 5)){
				Mca_installedDetector = detector;

				// Load DSP Program
				iReturn = McaLoadDSP();
				if(iReturn==0){
					MCASetHV(activeDetectorMirror->hv, TRUE);
					MCASetThreshold(activeDetectorMirror->threshold);
					Mca_setZeroOpAmpOffset(activeAutoCalMirror->zeroopampoffset);
					Mca_setGain(activeAutoCalMirror->gain1, activeAutoCalMirror->gain2);

					Mca_setAcquireTime(60);
					Mca_setTimeType(COUNT_LIVE);

#ifndef USE_T_WELL_AS_PROBE
					if(activeDetectorMirror == &detectorWell700Mirror) MCA_set700WellRelay(TRUE);
					else if(activeDetectorMirror == &detectorProbe700Mirror) MCA_set700WellRelay(FALSE);
#endif
				}else{
					Mca_installedDetector = DET_EMPTY;
				}
			}else if(detector == 0){
				iReturn = ERR_MCA_DETECTOR_NOT_ATTACHED;
				Mca_installedDetector = DET_EMPTY;
			}
			else{
				iReturn = ERR_MCA_UNKNOWN_DETECTOR;
				Mca_installedDetector = DET_EMPTY;
			}
		}else{
			// Return Error Code for unprogrammed MCA Board
			iReturn = ERR_MCA_EE_SIG_MISSING;
			Mca_installedDetector = DET_EMPTY;
		}
	}else{
		// Return Error Code for Missing MCA Board
		iReturn = ERR_MCA_NOT_INSTALLED;
		Mca_installedDetector = DET_EMPTY;
	}

	if(Mca_installedDetector != DET_EMPTY){
		fullSpecEffMirror = DB_ReadFullSpecEff(Mca_installedDetector);
	}else{
		fullSpecEffMirror = 0;
	}

	return iReturn;
}

