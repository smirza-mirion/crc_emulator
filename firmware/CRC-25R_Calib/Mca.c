bool Mca_findPeak(ulong spectrum[], ENERGYPEAK energyPeak[], bool sigmaLip, AUTOCAL *autocal){
	bool returnstatus;
	PEAK detectpeak[40];
	float upperLimit[40];
	float lowerLimit[40];
	float startEV, endEV;
	short startCH[40], endCH[40];
	float eV;
	short index, jndex, kndex, secondregionstart;
	bool found;
	AUTOCAL *autoCal;

	if(autocal == NULL) autoCal = activeAutoCalMirror;
	else autoCal = autocal;

	returnstatus = FALSE;
	Mca_getPeaks2(spectrum, detectpeak, & secondregionstart, autoCal->num_of_channels);
	Mca_dedupPeaks(detectpeak, secondregionstart, autoCal->num_of_channels);
	for(index=0; index<40; index++){
		if((detectpeak[index].centroid == 0) && (detectpeak[index].height == 0)){
			upperLimit[index] = -1.0;
			lowerLimit[index] = -1.0;
			startCH[index] = -1;
			endCH[index] = -1;
		}else{
			eV = Mca_convertChToEnergy(detectpeak[index].centroid, autoCal);
			Mca_getEnergyLimits(eV, &(lowerLimit[index]), &(upperLimit[index]), autoCal->num_of_channels);
			Mca_getEndPoints(eV, &startEV, &endEV, sigmaLip);
			Mca_getROIChannels(startEV, endEV, &(startCH[index]), &(endCH[index]), autoCal);
		}
	}

	for(index=0; index<10; index++){
		if(energyPeak[index].energy > 0){
			for(jndex=0; jndex<40; jndex++){
				if((energyPeak[index].energy>=lowerLimit[jndex]) && (energyPeak[index].energy<=upperLimit[jndex])){
					found = FALSE;
					for(kndex=0; kndex<10; kndex++){
						if(energyPeak[kndex].peakindex == jndex){
							found = TRUE;
							break;
						}
					}
					if(!found){
						energyPeak[index].peakindex = jndex;
						energyPeak[index].startCh = startCH[jndex];
						energyPeak[index].endCh = endCH[jndex];
						energyPeak[index].found = TRUE;
						break;
					}
				}
			}
		}
	}

	return returnstatus;
}

