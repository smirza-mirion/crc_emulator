int MCASetHV(short value, bool state){
	ushort ctl;
	ushort data;
	int returnstate;
	ushort origvalue;
	int temp_value;
	short corrected_value;

	Mca_stopAcquisition();
	MCASetAddress(MEAS_TIME_LOW_REG);	// Preserve MEAS_TIME_LOW_REG
	origvalue = MCAReadData();			// Preserve MEAS_TIME_LOW_REG

	if(value<0) corrected_value = 0;
	else if(value>4095) corrected_value = 4095;
	else corrected_value = value;

	if(state){
		// Turn On
		ctl = read_mca_port(DSPSYSCONTROL);
		ctl |= 0x80;
		write_mca_port(DSPSYSCONTROL, ctl);
		delay_msec(1);

		temp_value = HVValue;
		while(temp_value != corrected_value){
			if(temp_value < corrected_value){
				// Raise HV
				if((corrected_value - temp_value) > 100) temp_value += 100;
				else temp_value = corrected_value;
			}else if(temp_value > corrected_value){
				// Lower HV
				if((temp_value - corrected_value) > 100) temp_value -= 100;
				else temp_value = corrected_value;
			}

			MCASetAddress(DAC_DATA_REG);
			data = temp_value;
			data |= WRITE_HV;
			MCAWriteData(data);

			MCASetAddress(SW_CONTROL_REG);
			MCAWriteData(ZHT_DAC);
			returnstate = MCAWaitForFinish();

			delay_msec(5);
		}
		HVValue = corrected_value;
		HVState = TRUE;
		// Ramp to V
	}else{
		// Ramp to Zero V
		temp_value = HVValue;
		corrected_value = 0;
		while(temp_value != corrected_value){
			if((temp_value - corrected_value) > 100) temp_value -= 100;
			else temp_value = corrected_value;

			MCASetAddress(DAC_DATA_REG);
			data = temp_value;
			data |= WRITE_HV;
			MCAWriteData(data);

			MCASetAddress(SW_CONTROL_REG);
			MCAWriteData(ZHT_DAC);
			returnstate = MCAWaitForFinish();

			delay_msec(5);
		}

		// Turn Off
		ctl = read_mca_port(DSPSYSCONTROL);
		ctl &= 0x7F;
		write_mca_port(DSPSYSCONTROL, ctl);

		HVValue = 0;
		HVState = FALSE;
	}

	MCASetAddress(MEAS_TIME_LOW_REG);	// Preserve MEAS_TIME_LOW_REG
	MCAWriteData(origvalue);			// Preserve MEAS_TIME_LOW_REG

	return returnstate;
}

