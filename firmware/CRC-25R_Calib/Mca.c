static int MCAWaitForFinish(void){
	ushort ctl;
	ulong twosec;

	twosec = g_csec_tstamp + 200;
	do{
		MCASetAddress(SW_CONTROL_REG);
		ctl = MCAReadData();
		service_watchdog();
	}while(((ctl & 0x8000) == 0) && (twosec > g_csec_tstamp)); // Wait until bit15 is set, this signals that the DSP has finished an operation

	if((ctl & 0x8000) == 0x8000) return 0;
	else return ERR_MCA_COMMAND_TIMEOUT;
}

void MCACalcLinFactors(AUTOCAL *autoCal){
	short index;
	float nominator;
	float denominator;

	if(((autoCal->linmeasured[0])>0.0) && ((autoCal->linmeasured[1])>(autoCal->linmeasured[0])) && ((autoCal->linmeasured[2])>(autoCal->linmeasured[1])) && ((autoCal->linmeasured[3])>(autoCal->linmeasured[2])) && ((autoCal->linmeasured[4])>(autoCal->linmeasured[3]))){
		autoCal->linearityActive = TRUE;

		for(index=0; index<5; index++){
			autoCal->linMeas[index] = autoCal->linmeasured[index];
		}
		autoCal->linStd[0] = 32.85;
		autoCal->linStd[1] = 40.8;
		autoCal->linStd[2] = 121.8;
		autoCal->linStd[3] = 344.3;
		autoCal->linStd[4] = 661.66;

		nominator = autoCal->linStd[0];
		denominator = autoCal->linMeas[0];
		autoCal->factorMtoS[0] = nominator / denominator;
		autoCal->factorStoM[0] = denominator / nominator;

		for(index=1; index<5; index++){
			nominator = autoCal->linStd[index] - autoCal->linStd[index-1];
			denominator = autoCal->linMeas[index] - autoCal->linMeas[index-1];
			autoCal->factorMtoS[index] = nominator / denominator;
			autoCal->factorStoM[index] = denominator / nominator;
		}

		nominator = 2000.0 - (autoCal->linStd[4]);
		denominator = 2000.0 - (autoCal->linMeas[4]);

		autoCal->factorMtoS[5] = nominator / denominator;
		autoCal->factorStoM[5] = denominator / nominator;
	}else{
		autoCal->linearityActive = FALSE;
	}
}

