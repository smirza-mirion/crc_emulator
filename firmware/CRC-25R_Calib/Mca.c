void Mca_loadUncorrectedSpectrum(ulong spectra[4096], AUTOCAL *autocal, int NumOfChannels){
	short index;
	float channel;
	AUTOCAL *autoCal;

	if(autocal == NULL){
		autoCal = activeAutoCalMirror;
	}else{
		autoCal = autocal;
	}

	//Mca_numOfChannelsCorrection = autoCal->num_of_channels;
	Mca_numOfChannelsCorrection = NumOfChannels;
	for(index=0; index<Mca_numOfChannelsCorrection; index++){
		Mca_spectraCorrection[index] = spectra[index];
		channel = index;
		Mca_keVCorrection[index] = Mca_convertChToEnergyWithExplicitNumOfCh(channel, autoCal, NumOfChannels);
	}
}

//Modified
float Mca_getCorrectedSpectra(float eV){
	short index;
	float returnvalue;
	float slope, counts1, counts0, denomin, numer, energydelta;

	if(eV<=0.0){
		returnvalue = Mca_spectraCorrection[0];
	}else if(eV>=2000.0){
		returnvalue = Mca_spectraCorrection[Mca_numOfChannelsCorrection - 1];
	}else{
		index = 0;
		while((index<Mca_numOfChannelsCorrection) && Mca_keVCorrection[index] < eV) index++;
		if(Mca_keVCorrection[index] == eV){
			returnvalue = Mca_spectraCorrection[index];
		}else{
			counts0 = Mca_spectraCorrection[index - 1];
			counts1 = Mca_spectraCorrection[index];
			numer = counts1 - counts0;
			denomin = Mca_keVCorrection[index] - Mca_keVCorrection[index - 1];
			slope = numer / denomin;
			energydelta = eV - Mca_keVCorrection[index - 1];
			returnvalue = slope * energydelta + counts0;
		}
	}

	return returnvalue;
}

