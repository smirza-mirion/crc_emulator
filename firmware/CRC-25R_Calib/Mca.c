void Mca_getEnergyLimits(float energy, float *lowerLimit, float *upperLimit, int numOfChannels){
	float tolerance, energyDifference, toleranceFloor, maxChannel;

	maxChannel = numOfChannels - 1;
	toleranceFloor = 2000.0;
	toleranceFloor /= maxChannel;
	toleranceFloor *= 2.0; // Two channels
	tolerance = .05; // 5%

	energyDifference = energy * tolerance;
	if(energyDifference < toleranceFloor) energyDifference = toleranceFloor;
	*lowerLimit = energy - energyDifference;
	if(*lowerLimit < 0) *lowerLimit = 0;
	*upperLimit = energy + energyDifference;
}

