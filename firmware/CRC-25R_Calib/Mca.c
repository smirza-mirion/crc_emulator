void Mca_getWipePeak(DB_SPEC *spectrum, PEAK detectpeak[], WELLWIPEPEAK wipepeak[]){
	short index, jndex, startCh, endCh;
	float detectpeakcentroid, detectpeakenergy, startEV, endEV;
	int iROICounts, iBackCounts;

	for(index=0; index<40; index++){
		wipepeak[index].WellWipePeakID = 0;
		wipepeak[index].WellWipeID = 0;
		wipepeak[index].Energy = -1.0;
		wipepeak[index].StartROI = -1.0;
		wipepeak[index].EndROI = -1.0;
		wipepeak[index].ROICounts = 0;
		wipepeak[index].ROICPM = 0.0;
		wipepeak[index].BackgroundROICounts = 0;
		wipepeak[index].BackgroundROICPM  = 0.0;
		wipepeak[index].NetROICPM = 0.0;
		wipepeak[index].WellWipeNuclideID = 0;
		wipepeak[index].Activity = -1000000.0;
		wipepeak[index].ExceedsThreshold = FALSE;
		wipepeak[index].PeakType = NOT_FOUND;
	}

	for(index=0; index<40; index++){
		if(detectpeak[index].height>0.0){
			detectpeakcentroid = detectpeak[index].centroid;
			detectpeakenergy = Mca_convertChToEnergy(detectpeakcentroid, NULL);
			wipepeak[index].Energy = detectpeakenergy;
			Mca_getEndPoints(detectpeakenergy, &startEV, &endEV, FALSE);
			wipepeak[index].StartROI = startEV;
			wipepeak[index].EndROI = endEV;
			Mca_getROIChannels(startEV, endEV, &startCh, &endCh, NULL);

			iROICounts = 0;
			iBackCounts = 0;
			for(jndex=startCh; jndex<=endCh; jndex++){
				iROICounts += spectrum->DecompressedSpectra[jndex];
				iBackCounts += activeBkgMirror->Spectrum.DecompressedSpectra[jndex];
			}

			wipepeak[index].ROICounts = iROICounts;
			wipepeak[index].ROICPM = iROICounts;
			wipepeak[index].ROICPM /= spectrum->LiveTime;
			wipepeak[index].ROICPM *= 60.0;

			wipepeak[index].BackgroundROICounts = iBackCounts;
			wipepeak[index].BackgroundROICPM = iBackCounts;
			wipepeak[index].BackgroundROICPM /= activeBkgMirror->Spectrum.LiveTime;
			wipepeak[index].BackgroundROICPM *= 60.0;

			wipepeak[index].NetROICPM = wipepeak[index].ROICPM - wipepeak[index].BackgroundROICPM;
		}else{
			break;
		}
	}
}

