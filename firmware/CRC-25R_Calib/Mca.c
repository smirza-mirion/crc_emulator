static void MCA_set700WellRelay(bool Well){
	ushort ctl;

	ctl = read_mca_port(DSPSYSCONTROL);

	if(Well){
		ctl |= 0x01;
	}else{
		ctl &= 0xFE;
	}
	write_mca_port(DSPSYSCONTROL, ctl);
}

void Mca_switchDetector(short newDetector){
	Mca_installedDetector = newDetector;
	switch(Mca_installedDetector){
		case DET_PROBE700:
			activeDetectorMirror = &detectorProbe700Mirror;
			activeAutoCalMirror = &probe700AutoCalMirror;
			activeBkgMirror = &probe700BkgMirror;
			MCA_set700WellRelay(FALSE); // Probe is not Well
			break;

		case DET_DRILLEDPROBE700:
			activeDetectorMirror = &detectorProbe700Mirror;
			activeAutoCalMirror = &drilledprobe700AutoCalMirror;
			activeBkgMirror = &drilledprobe700BkgMirror;
			MCA_set700WellRelay(FALSE); // Probe is not Well
			break;

		case DET_WELL700:
			activeDetectorMirror = &detectorWell700Mirror;
			activeAutoCalMirror = &well700AutoCalMirror;
			activeBkgMirror = &well700BkgMirror;
			MCA_set700WellRelay(TRUE); // Well relay is on
			break;
	}

	MCASetHV(activeDetectorMirror->hv, TRUE);
	MCASetThreshold(activeDetectorMirror->threshold);
	Mca_setZeroOpAmpOffset(activeAutoCalMirror->zeroopampoffset);
	Mca_setGain(activeAutoCalMirror->gain1, activeAutoCalMirror->gain2);
}

